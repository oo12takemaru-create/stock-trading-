# -*- coding: utf-8 -*-
"""株式分割の部品のテスト（表題の分類・本文の読み取り・権利付き最終日・JPX一覧の読み取り）

本文の例は 2026-10 の実物の開示から、値を読むのに要る部分だけを書き写したもの（PDFは置かない）。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import split_extract as X   # noqa: E402

NG = 0


def eq(got, want, label):
    global NG
    if got != want:
        NG += 1
        print(f"  NG {label}\n     期待={want}\n     実際={got}")


# ── 表題の分類
for title, want in [
    ("株式分割、株式分割に伴う定款の一部変更及び株主優待制度の変更（拡充）に関するお知らせ", "split"),
    ("株式分割及び定款の一部変更並びに配当予想の修正に関するお知らせ", "split"),
    ("株式分割及び株式分割に伴う定款の一部変更に関するお知らせ", "split"),
    ("株式の分割及び定款の一部変更に関するお知らせ", "split"),
    ("（訂正）株式分割及び株式分割に伴う定款の一部変更に関するお知らせ", "correction"),
    ("株式分割の中止に関するお知らせ", "cancel"),
    ("株式分割に伴う配当予想の修正に関するお知らせ", "related"),
    ("株式分割に伴う新株予約権の行使価額の調整に関するお知らせ", "related"),
    ("連結子会社との会社分割（簡易吸収分割）に関するお知らせ", None),
    ("会社分割（新設分割）に関する基本方針決定のお知らせ", None),
    ("ライセンス契約収益（Sancuso分割契約金）計上", None),
    ("株式併合並びに単元株式数の定めの廃止及び定款の一部変更に関するお知らせ", "reverse"),
    ("株式無償割当てに関するお知らせ", "gratis"),
    ("新株予約権無償割当てに関するお知らせ", None),
]:
    eq(X.classify(title), want, f"classify {title}")

# ── 本文の読み取り（光フードサービス 2026-10-14：日程表が上に来て「基準日公告日」が先に出る型）
T1 = """株式分割前の発行済株式総数 992,000株 今回の分割により増加する株式数 992,000株
株式分割後の発行済株式総数 1,984,000株 基準日公告日(予定) 2026年11月13日 基準日 2026年11月30日
効力発生日 2026年12月1日 (2)分割の方法 2026年11月30日を基準日として、同日最終の株主名簿に記載又は
記録された株主の所有する当社普通株式1株につき、2株の割合をもって分割いたします。"""
r = X.extract(T1)
eq((r["ratio"], r["record"], r["effective"], r["extract_ok"]), (2, "2026-11-30", "2026-12-01", True), "光フード")

# エクシオHD 2026-10-15（曜日つき・10倍）
T2 = """1分割の方法 2026年10月31日(土曜日)を基準日とし、同日最終の株主名簿に記載又は記録された株主の所有する
普通株式1株につき、10株の割合をもって分割いたします。株式分割前の発行済株式総数 210,000株
株式分割後の発行済株式総数 2,100,000株 3分割の日程 基準日公告日 2026年10月15日(木曜日)
基準日 2026年10月31日(土曜日) 効力発生日 2026年11月2日(月曜日)"""
r = X.extract(T2)
eq((r["ratio"], r["record"], r["effective"], r["extract_ok"]), (10, "2026-10-31", "2026-11-02", True), "エクシオ")

# 同じ会社の訂正（訂正後だけを読む。比率は書かれていないので None＝元の値を残す）
T3 = """【訂正箇所及び訂正内容】 3分割の日程 (訂正前) 基準日公告日 2026年10月15日(木曜日) 基準日 2026年10月31日(土曜日)
効力発生日 2026年11月2日(月曜日) (訂正後) 基準日公告日 2026年10月15日(木曜日) 基準日 2026年10月31日(土曜日)
効力発生日 2026年11月1日(日曜日)"""
r = X.extract(T3)
eq((r["ratio"], r["record"], r["effective"], r.get("corrected_part")), (None, "2026-10-31", "2026-11-01", True), "エクシオ訂正")

# メイコー 2026-09-28（「1株に付き」・基準日が日曜）
r = X.extract("2026年11月1日(日)を基準日として、同日最終の株主名簿に記載又は記録された株主の所有する当社普通株式を、"
              "1株に付き2株の割合をもって分割いたします。基準日 2026年11月1日(日) 効力発生日 2026年11月2日(月)")
eq((r["ratio"], r["record"], r["effective"]), (2, "2026-11-01", "2026-11-02"), "メイコー")
eq(X.kenri_last("2026-11-01"), ("2026-10-28", "2026-10-29"), "基準日 11/1(日)")

# 文と日程表の基準日が食い違ったら入れない
r = X.extract(T1.replace("基準日 2026年11月30日", "基準日 2026年11月27日"))
eq(r["record"], None, "基準日の食い違い")

# ── 権利付き最終日（基準日の2営業日前・基準日が休みならその前の営業日から数える）
eq(X.kenri_last("2026-11-30"), ("2026-11-26", "2026-11-27"), "基準日 11/30(月)")
eq(X.kenri_last("2026-10-31"), ("2026-10-28", "2026-10-29"), "基準日 10/31(土)")
eq(X.kenri_last("2026-11-25"), ("2026-11-20", "2026-11-24"), "基準日 11/25(水)・11/23 勤労感謝の日をまたぐ")
eq(X.kenri_last("2026-12-31"), ("2026-12-28", "2026-12-29"), "基準日 12/31（大納会は12/30）")
eq(X.kenri_last("2016-03-31"), ("2016-03-28", "2016-03-29"), "2016年は T+3")

