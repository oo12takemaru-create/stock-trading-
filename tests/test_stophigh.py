# -*- coding: utf-8 -*-
"""制限値幅・呼値の単位・ストップ高の判定のテスト

表は JPX 公式（2026-10-24 確認）
  制限値幅 https://www.jpx.co.jp/equities/trading/domestic/06.html
  呼値の単位 https://www.jpx.co.jp/equities/trading/domestic/07.html
帯の境目（「未満」と「以下」の違い）を取り違えると、その帯の銘柄が全部ずれるので境目を固定値で持つ。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from stophigh import classify, limit_width, stop_prices, tick   # noqa: E402

NG = 0


def eq(got, want, label):
    global NG
    if got != want:
        NG += 1
        print(f"  NG {label}\n     期待={want}\n     実際={got}")


# 制限値幅: 基準値段 X円「未満」
for base, w in [(99, 30), (99.9, 30), (100, 50), (199, 50), (200, 80), (499, 80), (500, 100), (699, 100),
                (700, 150), (999, 150), (1000, 300), (1499, 300), (1500, 400), (1999, 400), (2000, 500),
                (2999, 500), (3000, 700), (4999, 700), (5000, 1000), (6999, 1000), (7000, 1500),
                (9999, 1500), (10000, 3000), (14999, 3000), (15000, 4000), (20000, 5000), (30000, 7000),
                (50000, 10000), (70000, 15000), (100000, 30000), (150000, 40000), (200000, 50000),
                (300000, 70000), (500000, 100000), (700000, 150000), (1000000, 300000),
                (1500000, 400000), (2000000, 500000), (3000000, 700000), (5000000, 1000000),
                (7000000, 1500000), (10000000, 3000000), (15000000, 4000000), (20000000, 5000000),
                (30000000, 7000000), (49999999, 7000000), (50000000, 10000000)]:
    eq(limit_width(base), w, f"制限値幅 {base}")

# 呼値の単位: 値段 X円「以下」
for p, t5, to in [(1000, 0.1, 1), (1000.5, 0.5, 1), (3000, 0.5, 1), (3001, 1, 5), (5000, 1, 5), (5001, 1, 10),
                  (10000, 1, 10), (10001, 5, 10), (30000, 5, 10), (30001, 10, 50), (50000, 10, 50),
                  (50001, 10, 100), (100000, 10, 100), (100001, 50, 100), (300001, 100, 500),
                  (500001, 100, 1000), (1000001, 500, 1000), (3000001, 1000, 5000), (5000001, 1000, 10000),
                  (10000001, 5000, 10000), (30000001, 10000, 50000), (50000001, 10000, 100000)]:
    eq(tick(p, True), t5, f"呼値 TOPIX500 {p}")
    eq(tick(p, False), to, f"呼値 その他 {p}")

# ストップ高・安の値段（呼値の単位に丸める）
eq(stop_prices(500, False), (600, 400), "500円 → 600 / 400")
eq(stop_prices(499, False), (579, 419), "499円 → 579 / 419")
eq(stop_prices(4995, False), (5700, 4295), "4,995円（その他）: 5,695 は10円刻み → 1つ上の 5,700")
eq(stop_prices(4995, True), (5695, 4295), "4,995円（TOPIX500）: 1円刻みなので 5,695")
eq(stop_prices(2800, False), (3300, 2300), "2,800円 → 3,300 / 2,300")
eq(stop_prices(2600.5, True), (3101, 2100.5), "2,600.5円（TOPIX500）→ 3,100.5 は1円刻みの帯 → 3,101")
eq(stop_prices(9990, False), (11490, 8490), "9,990円 → 11,490 / 8,490")
eq(stop_prices(29995, True), (35000, 24995), "29,995円（TOPIX500）→ 34,995 は10円刻み → 35,000")
eq(stop_prices(20, False), (50, None), "20円 → 下限なし（0円以下）")

# 実際の約定で確かめた例（2026-10-24・stophigh.stop_prices の注記）
eq(stop_prices(2759, False)[0], 3260, "1847 2026-08-07 基準2,759円 → 3,260円で約定")
eq(stop_prices(2896, False)[0], 3400, "2121 2026-08-03 基準2,896円 → 3,400円")
eq(stop_prices(4455, False)[0], 5160, "3131 2026-08-10 基準4,455円 → 5,160円")
eq(stop_prices(2913, False)[0], 3415, "135A 2026-04-15 基準2,913円 → 3,415円")

# 判定
eq(classify(500, 560, 600, 550, 600, False)[0], "close_high", "終値ストップ高")
eq(classify(500, 560, 600, 550, 590, False)[0], "touch_high", "一時ストップ高")
eq(classify(500, 450, 460, 400, 400, False)[0], "close_low", "終値ストップ安")
eq(classify(500, 450, 460, 400, 420, False)[0], "touch_low", "一時ストップ安")
eq(classify(500, 600, 700, 600, 700, False)[0], "out", "上限を超えた（拡大・調整）→ 判定しない")
eq(classify(500, 510, 520, 490, 505, False)[0], None, "ふつうの日")

# 制限値幅の拡大（JPX マーケットニュースの本文。2024-03-12 住石HD・2026-10-19 オンデックの書き方）
from stophigh import parse_kakudai_news   # noqa: E402
html1 = ("<p>翌営業日（13日）においては、以下のとおり、制限値幅の上限（下限）を拡大</p>"
         "<p>住石ホールディングス（株）　株式（コード　1514）<br>制限値幅（下限）：2,000円（上限は通常どおり500円）<br>"
         "基準値段：2,770円、ストップ高：3,270円、ストップ安：770円</p><p>（注1）3月13日以降</p>")
eq(parse_kakudai_news(html1, "https://www.jpx.co.jp/news/1030/20240312-01.html"),
   [{"d": "2024-03-13", "c": "1514", "side": "下限", "w": 2000.0, "base": 2770.0, "up": 3270.0, "lo": 770.0,
     "news": "2024-03-12", "src": "https://www.jpx.co.jp/news/1030/20240312-01.html"}], "拡大のニュース（下限）")
html2 = ("<p>翌営業日（20日）においては</p><p>（株）オンデック　株式（コード　7360）制限値幅（上限）：600円（下限は通常どおり150円）"
         "基準値段：861円、ストップ高：1,461円、ストップ安：711円</p>（注1）")
eq([(x["d"], x["c"], x["up"], x["lo"]) for x in parse_kakudai_news(html2, "https://www.jpx.co.jp/news/1030/20261019-01.html")],
   [("2026-10-20", "7360", 1461.0, 711.0)], "拡大のニュース（上限）")
eq(classify(861, 1461, 1461, 1461, 1461, False, lim=(1461, 711))[0], "close_high", "拡大後の値段で終値ストップ高")

# 追記のみの記録の重ね方: 値幅拡大の行は先の行より優先・void は消す
from stophigh import merge   # noqa: E402
m = merge([{"t": "ev", "d": "2026-10-20", "c": "1", "k": "touch_high"},
           {"t": "ev", "d": "2026-10-20", "c": "1", "k": "close_high", "kakudai": True},
           {"t": "ev", "d": "2026-10-21", "c": "2", "k": "close_low"},
           {"t": "void", "d": "2026-10-21", "c": "2"},
           {"t": "fu", "d": "2026-10-20", "c": "1", "n1o": 1.0}])
eq(sorted((k, v["k"], v.get("fu", {}).get("n1o")) for k, v in m.items()),
   [(("2026-10-20", "1"), "close_high", 1.0)], "値幅拡大の行で上書き・void で消える")

print("OK" if NG == 0 else f"NG {NG}件")
sys.exit(1 if NG else 0)
