# 自動規則で取り除く語（長いものから）
DROP = ["ホールディングス", "ホールディング", "グループ本社", "グループ", "株式会社", "（株）", "(株)",
        " Technology", " Group", "HD"]


def _w(ch):
    return 0.5 if ord(ch) < 0x100 or 0xFF61 <= ord(ch) <= 0xFF9F else 1.0


def width(s):
    return sum(_w(ch) for ch in s)


def _half(s):
    # 全角英数だけ半角に（カタカナ・記号はそのまま）
    return "".join(unicodedata.normalize("NFKC", ch) if ch.isalnum() and 0xFF10 <= ord(ch) <= 0xFF5A else ch
                   for ch in s)


def auto(name):
    s = _half(name)
    for w in DROP:
        s = s.replace(w, "")
    s = s.strip(" ・")
    out, w = "", 0.0
    for ch in s:
        if w + _w(ch) > MAX_W:
            break
        out += ch
        w += _w(ch)
    return out.strip(" ・") or _half(name)[:5]


def abbr(code, name):
    """略称。辞書にあればそれ、無ければ自動規則"""
    return ABBR.get(code) or auto(name)


