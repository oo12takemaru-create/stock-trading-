/**
 * 東証の休場日（土日を除く）。
 *
 * ■ なぜ静的表か
 * `docs/` に営業日カレンダーが無く、外部APIを増やしたくないため
 * （企画書v2 §14「新規の外部サービスは入れない」）。
 * 祝日は前年に官報で確定するので、年1回の手作業で足りる。
 *
 * ■ 切れたらどうなるか
 * 表に無い年は「休場日が1つも無い」＝**平日は全部動く**扱いになる。
 * 止まるのではなく余計に動く側に倒してある（冪等ガードが効くので害は小さい）。
 * ただし気づけないと困るので、`isKnownYear()` で表の範囲外を判定でき、
 * Worker のログと /health に出す。
 *
 * 出典: JPX「取引カレンダー」。年末年始（12/31〜1/3）は毎年休場。
 */

/** JPX の休場日（YYYY-MM-DD）。土日は含めない（曜日で判定するため） */
export const HOLIDAYS = new Set([
  // ---- 2026年 ----
  "2026-01-01", "2026-01-02", "2026-01-12", // 元日/年始/成人の日
  "2026-02-11", "2026-02-23",               // 建国記念の日/天皇誕生日
  "2026-03-20",                             // 春分の日
  "2026-04-29",                             // 昭和の日
  "2026-05-04", "2026-05-05", "2026-05-06", // みどりの日/こどもの日/振替
  "2026-07-20",                             // 海の日
  "2026-08-11",                             // 山の日
  "2026-09-21", "2026-09-22", "2026-09-23", // 敬老の日/国民の休日/秋分の日
  "2026-10-12",                             // スポーツの日
  "2026-11-03", "2026-11-23",               // 文化の日/勤労感謝の日
  "2026-12-31",                             // 大納会の翌日から年末休場
  // ---- 2027年 ----
  "2027-01-01",
]);

/** 表が対応している年（この範囲外は休場日を知らない） */
export const KNOWN_YEARS = [2026, 2027];

export function isKnownYear(ymd) {
  const y = Number(String(ymd).slice(0, 4));
  return KNOWN_YEARS.includes(y);
}

/** 東証が開いている日か（土日と休場日を除く） */
export function isTradingDay(jst) {
  const dow = jst.getUTCDay(); // jst は「JSTの壁時計をUTCとして持つ」Date
  if (dow === 0 || dow === 6) return false;
  return !HOLIDAYS.has(ymd(jst));
}

/** JST の Date を YYYY-MM-DD にする */
export function ymd(jst) {
  return jst.toISOString().slice(0, 10);
}
